package io.heapy.komok.tech.runtime.ksp

import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.MAP
import com.squareup.kotlinpoet.MUTABLE_MAP
import com.squareup.kotlinpoet.MemberName
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.STAR
import com.squareup.kotlinpoet.TypeName

/** Fully-qualified names of the annotations and runtime types the processor references. */
internal object WellKnownTypes {
    const val MODULE_ANNOTATION = "io.heapy.komok.tech.runtime.Module"
    const val SERVICE_ANNOTATION = "io.heapy.komok.tech.runtime.Service"
    const val INTO_SET_ANNOTATION = "io.heapy.komok.tech.runtime.IntoSet"
    const val BINDING_INDEX_ANNOTATION = "io.heapy.komok.tech.runtime.KomokBindingIndex"
    const val PROVIDERS_FROM_ANNOTATION = "io.heapy.komok.tech.runtime.ProvidersFrom"
    const val GENERATE_MOCK_ANNOTATION = "io.heapy.komok.tech.runtime.GenerateMock"

    private const val RUNTIME = "io.heapy.komok.tech.runtime"

    val komokRuntime = ClassName(RUNTIME, "KomokRuntime")
    val komokContext = ClassName(RUNTIME, "KomokContext")
    val bindingId = ClassName(RUNTIME, "BindingId")
    val providerSignature = ClassName(RUNTIME, "ProviderSignature")
    val realmHandle = ClassName(RUNTIME, "RealmHandle")
    val bindingOverride = ClassName(RUNTIME, "BindingOverride")
    val lifecycle = ClassName(RUNTIME, "Lifecycle")
    val lifecycleRegistry = ClassName(RUNTIME, "LifecycleRegistry")
    val lifecyclePhase = ClassName(RUNTIME, "LifecyclePhase")
    val graphPayload = ClassName(RUNTIME, "GraphPayload")
    val moduleDescriptor = ClassName(RUNTIME, "ModuleDescriptor")
    val komokBindingIndex = ClassName(RUNTIME, "KomokBindingIndex")
    val edgeDescriptors = MemberName(RUNTIME, "edgeDescriptors")
    val realized = MemberName(RUNTIME, "realized")

    val coroutineDispatcher = ClassName("kotlinx.coroutines", "CoroutineDispatcher")
    val dispatchers = ClassName("kotlinx.coroutines", "Dispatchers")
    val coroutineContext = ClassName("kotlin.coroutines", "CoroutineContext")
    val emptyCoroutineContext = ClassName("kotlin.coroutines", "EmptyCoroutineContext")

    private const val WRAPPERS = "io.heapy.komok.tech.runtime.wrappers"

    // Wrapper helper/context types live in the WrapperPlugin implementations; only the
    // meta model generated by the core is referenced here.
    val methodMeta = ClassName(WRAPPERS, "MethodMeta")
    val parameterMeta = ClassName(WRAPPERS, "ParameterMeta")

    private val bindingOverrideStar: TypeName = bindingOverride.parameterizedBy(STAR)

    /** `Map<BindingId, BindingOverride<*>>` — the read-only fork override map. */
    val overridesMap: TypeName = MAP.parameterizedBy(bindingId, bindingOverrideStar)

    /** `MutableMap<BindingId, BindingOverride<*>>` — the builder-side override map. */
    val mutableOverridesMap: TypeName = MUTABLE_MAP.parameterizedBy(bindingId, bindingOverrideStar)
}
